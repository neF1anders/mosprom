from __future__ import annotations

import builtins
from collections.abc import Callable
from types import TracebackType
from typing import Any, Protocol

from ..domain.models import Attachment, Event, Job, JobHead, Knowledge, Message, Work


class Jobs(Protocol):
    async def head(self, job_id: str) -> JobHead: ...
    async def get(self, job_id: str, *, lock: bool = False) -> Job: ...
    async def save(self, job: Job) -> None: ...
    async def list(self, before: str | None = None, limit: int = 50) -> builtins.list[Job]: ...
    async def message(self, message: Message) -> None: ...
    async def messages(
        self, job_id: str, before: int | None = None, limit: int = 100
    ) -> builtins.list[dict[str, Any]]: ...
    async def attachment(self, attachment: Attachment) -> None: ...
    async def attachments(self, job_id: str) -> builtins.list[Attachment]: ...
    async def receipt(self, key: str, payload_hash: str) -> dict[str, Any] | None: ...
    async def remember(self, key: str, payload_hash: str, result: dict[str, Any]) -> None: ...
    async def cache(self, key: str) -> dict[str, Any] | None: ...
    async def cache_put(self, key: str, value: dict[str, Any]) -> None: ...
    async def card_version(self, job: Job) -> None: ...


class Events(Protocol):
    async def append(self, event: Event) -> None: ...
    async def list(self, job_id: str, after: int = 0, limit: int = 100) -> builtins.list[Event]: ...


class Queue(Protocol):
    async def enqueue(self, job: Job) -> None: ...
    async def claim(self, owner: str, lease_seconds: int = 30) -> Work | None: ...
    async def heartbeat(self, work: Work, lease_seconds: int = 30) -> bool: ...
    async def finish(self, work: Work) -> None: ...


class Library(Protocol):
    async def search(
        self,
        query: str,
        material_id: str | None = None,
        property_name: str | None = None,
        offset: int = 0,
    ) -> builtins.list[Knowledge]: ...
    async def put(self, record: Knowledge) -> None: ...


class UnitOfWork(Protocol):
    jobs: Jobs
    events: Events
    queue: Queue
    knowledge: Library

    async def __aenter__(self) -> "UnitOfWork": ...
    async def __aexit__(
        self,
        exc_type: type[BaseException] | None,
        exc: BaseException | None,
        tb: TracebackType | None,
    ) -> None: ...
    async def commit(self) -> None: ...


UowFactory = Callable[[], UnitOfWork]
